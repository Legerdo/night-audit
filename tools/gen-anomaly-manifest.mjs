// Writes docs/anomaly-manifest.json from the live registry (src/data/anomalies.ts) plus the story
// slots that place them, so the document can never drift from the code.
// usage: node tools/gen-anomaly-manifest.mjs
import { createServer } from 'vite';
import fs from 'node:fs';

const server = await createServer({ server: { middlewareMode: true }, appType: 'custom', logLevel: 'error' });
try {
  const { ANOMALIES, CATEGORY_LABEL } = await server.ssrLoadModule('/src/data/anomalies.ts');
  const { SLOTS, OPTIONALS } = await server.ssrLoadModule('/src/data/story.ts');
  const storySlot = new Map(SLOTS.filter((s) => s.anomaly).map((s) => [s.anomaly, s.id]));
  const optSlot = new Map(OPTIONALS.map((o) => [o.anomaly, o.id]));
  const byCat = {};
  const byDiff = {};
  const entries = ANOMALIES.map((a) => {
    byCat[a.category] = (byCat[a.category] ?? 0) + 1;
    byDiff[a.difficulty] = (byDiff[a.difficulty] ?? 0) + 1;
    return {
      id: a.id,
      title: a.title,
      category: a.category,
      reportCategory: CATEGORY_LABEL[a.category],
      acceptAlso: a.accept ?? [],
      difficulty: a.difficulty,
      location: a.loc,
      floors: a.floors ?? null,
      baselineState: a.baselineState,
      anomalyState: a.anomalyState,
      intendedDifference: a.intendedDifference,
      forbiddenDifferences: a.forbiddenDifferences,
      detectionChannels: a.channels,
      detection: a.detection,
      realisation: a.realisation,
      resetRule: a.resetRule,
      persistent: a.persistent,
      contaminationImpact: a.contaminationImpact,
      requires: a.requires ?? [],
      acts: [a.minAct, a.maxAct ?? 4],
      placement: storySlot.has(a.id) ? `story:${storySlot.get(a.id)}` : optSlot.has(a.id) ? `optional:${optSlot.get(a.id)}` : 'random-pool',
      imagePair: a.imagePair ?? null,
      purpose: a.purpose,
    };
  });
  const doc = {
    note: 'Generated by tools/gen-anomaly-manifest.mjs from src/data/anomalies.ts and src/data/story.ts. Do not edit by hand.',
    count: entries.length,
    byCategory: byCat,
    byDifficulty: byDiff,
    anomalies: entries,
  };
  fs.mkdirSync('docs', { recursive: true });
  fs.writeFileSync('docs/anomaly-manifest.json', JSON.stringify(doc, null, 2) + '\n');
  console.log(`wrote docs/anomaly-manifest.json (${entries.length} anomalies)`, JSON.stringify(byCat), JSON.stringify(byDiff));
} finally {
  await server.close();
}
