"""Write docs/image-prompts.md from art/prompts/*.txt, art/export.json and art/pairs.json.

Every prompt that produced a shipped asset is listed with its runtime path, the reference image used
for edits, QA results for anomaly pairs, and rejected attempts.
usage: python tools/imageqa/gen_prompts_doc.py
"""
import io
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def rd(p):
    with io.open(os.path.join(ROOT, p), encoding="utf-8") as f:
        return f.read()


export = json.loads(rd("art/export.json"))["assets"]
pairs = {p["id"]: p for p in json.loads(rd("art/pairs.json"))["pairs"]}
used = set()
out = [
    "# 이미지 프롬프트 기록 (Image prompts)",
    "",
    "Generated by `tools/imageqa/gen_prompts_doc.py`. Generation path: Codex CLI built-in `image_gen` via",
    "`tools/imagegen/codex-image.ps1` (see docs/validation.md for the exact tool/model facts).",
    "Anomaly images were always produced as **edits of the approved normal master** (`-RefImage`), never",
    "generated independently. Korean text is never generated by the model; all in-game text is drawn by code.",
    "",
]
for a in export:
    prompt = a.get("prompt")
    out.append(f"## `{a['key']}` — {a['role']}")
    out.append("")
    out.append(f"- runtime: `public/assets/images/{a['out']}`")
    out.append(f"- source: `{a['src']}`")
    if a.get("pair"):
        p = pairs[a["pair"]]
        m = os.path.join(ROOT, "art", "qa", a["pair"], "metrics.json")
        met = json.loads(rd(os.path.relpath(m, ROOT))) if os.path.exists(m) else {}
        out.append(f"- reference (edit input): `{p['normal']}`")
        out.append(f"- intended difference: {p['intended']}")
        out.append(f"- ROI (x0,y0,x1,y1 fractions): `{p['roi']}`; composite outside ROI from normal: {p.get('composite', False)}")
        out.append(
            f"- QA: changed inside ROI {met.get('changed_inside_roi_frac')}, outside ROI {met.get('changed_outside_roi_frac')}, "
            f"raw edit pass {met.get('raw_edit_pass')}, composite pass {met.get('composite_pass', 'n/a')}, alignment {met.get('align', {}).get('ecc', 'ecc ok')}"
        )
        for r in p.get("rejected", []):
            out.append(f"- rejected attempt: `{r['file']}` — {r['reason']}")
    out.append(f"- approved: {a.get('approved')}")
    if prompt and os.path.exists(os.path.join(ROOT, prompt)):
        used.add(os.path.basename(prompt))
        out.append(f"- prompt file: `{prompt}`")
        out.append("")
        out.append("```text")
        out.append(rd(prompt).strip())
        out.append("```")
    out.append("")

extra = sorted(set(os.listdir(os.path.join(ROOT, "art", "prompts"))) - used)
if extra:
    out.append("## Prompts not used by a shipped asset")
    out.append("")
    out.append("These produced rejected attempts (see the `rejected` entries above); they are kept for the record.")
    out.append("")
    for e in extra:
        out.append(f"### `art/prompts/{e}`")
        out.append("")
        out.append("```text")
        out.append(rd(f"art/prompts/{e}").strip())
        out.append("```")
        out.append("")

with io.open(os.path.join(ROOT, "docs", "image-prompts.md"), "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(out))
print("wrote docs/image-prompts.md", len(export), "assets,", len(extra), "unused prompts")
